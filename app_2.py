CHUNK_SIZE = 5000  # number of comments per chunk
LABELED_JSON = "labeled_comments.json"
LABELED_CSV = "labeled_comments.csv"

def save_results(records, json_path, csv_path):
    with open(json_path, "w", encoding="utf-8") as f_json:
        json.dump([r.to_dict() for r in records], f_json, indent=2)
    with open(csv_path, "w", encoding="utf-8", newline="") as f_csv:
        writer = csv.DictWriter(f_csv, fieldnames=list(records[0].to_dict().keys()) if records else [])
        writer.writeheader()
        for r in records:
            writer.writerow(r.to_dict())
    print(f"Saved results: {json_path} + {csv_path}")

# ==== UPDATED FUNCTIONS ====
def process_repo(repo_path, repo_name):
    print(f"🔹 Processing repo: {repo_name}")
    records = []
    all_files = find_all_java_files(repo_path)
    for idx, file_path in enumerate(all_files, 1):
        print(f"  [{idx}/{len(all_files)}] {file_path}")
        comments = extract_class_comments(file_path)
        commit_hash, commit_date, commit_msg = get_last_commit(file_path, repo_path)
        for class_name, comment_text, level, start_line, end_line in comments:
            label, reason = determine_label_debug(commit_date, comment_text)
            rec = CommentRecord(
                repo_name, os.path.relpath(file_path, repo_path),
                class_name, comment_text, level, start_line, end_line,
                commit_hash, commit_date, commit_msg, label
            )
            # Add debug info
            rec.debug_reason = reason
            records.append(rec)
    print(f"Extracted {len(records)} class-level comments from {repo_name}\n")
    return records

def save_chunks(records, base_name="combined_comments", chunk_size=CHUNK_SIZE):
    for i in range(0, len(records), chunk_size):
        chunk = records[i:i+chunk_size]
        chunk_idx = i // chunk_size + 1
        json_path = f"{base_name}_{chunk_idx}.json"
        csv_path = f"{base_name}_{chunk_idx}.csv"
        save_results(chunk, json_path, csv_path)

def save_labeled(records, json_path=LABELED_JSON, csv_path=LABELED_CSV):
    labeled_records = [r for r in records if r.label in ("human", "artificial_intelligence")]
    save_results(labeled_records, json_path, csv_path)
    print(f"Saved labeled human + AI comments: {json_path} + {csv_path}")


